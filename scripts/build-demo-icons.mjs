import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { momcozyIcons } from '../src/lib/icons.ts'

const outputUrl = new URL('../public/demos/_shared/momcozy-icons.js', import.meta.url)

const source = `/* Generated by scripts/build-demo-icons.mjs. Do not edit by hand. */
const MOMCOZY_ICONS = ${JSON.stringify(momcozyIcons)};

const SVG_ATTRIBUTE_NAMES = {
  className: 'class',
  fillRule: 'fill-rule',
  clipRule: 'clip-rule',
  strokeLinecap: 'stroke-linecap',
  strokeLinejoin: 'stroke-linejoin',
  strokeMiterlimit: 'stroke-miterlimit',
};

function escapeAttribute(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');
}

function renderNode([tag, attributes]) {
  const serialized = Object.entries(attributes)
    .filter(([name]) => name !== 'key' && name !== 'strokeWidth')
    .map(([name, value]) => {
      const attributeName = SVG_ATTRIBUTE_NAMES[name] || name.replace(/[A-Z]/g, (letter) => \`-\${letter.toLowerCase()}\`);
      return \`\${attributeName}="\${escapeAttribute(value)}"\`;
    })
    .join(' ');

  return \`<\${tag}\${serialized ? \` \${serialized}\` : ''}></\${tag}>\`;
}

class MomcozyIcon extends HTMLElement {
  static get observedAttributes() {
    return ['name', 'size', 'stroke-width'];
  }

  connectedCallback() {
    this.render();
  }

  attributeChangedCallback() {
    if (this.isConnected) this.render();
  }

  render() {
    const name = this.getAttribute('name');
    const icon = MOMCOZY_ICONS[name];

    if (!icon) {
      this.replaceChildren();
      console.warn(\`Unknown Momcozy icon: \${name}\`);
      return;
    }

    const size = escapeAttribute(this.getAttribute('size') || '1em');
    const strokeWidth = escapeAttribute(this.getAttribute('stroke-width') || '1.7');
    this.innerHTML = \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" color="currentColor" stroke-width="\${strokeWidth}" aria-hidden="true" focusable="false">\${icon.map(renderNode).join('')}</svg>\`;
  }
}

if (!customElements.get('momcozy-icon')) {
  customElements.define('momcozy-icon', MomcozyIcon);
}
`

await writeFile(fileURLToPath(outputUrl), source)
console.log(`Generated ${fileURLToPath(outputUrl)} with ${Object.keys(momcozyIcons).length} semantic icons.`)

